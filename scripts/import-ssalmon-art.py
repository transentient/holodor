#!/usr/bin/env python3
"""
import-ssalmon-art.py — One-command importer for ssalmon's 3 commission pieces:
  1. --icon <png>      (64x64 or 32x32 Holodor head icon -> BootHolodor.apk + docs)
  2. --splash <png>    (240x135 Act 1 boot picture -> OpenABL Menu/BootSplash.c @ 8x)
  3. --wordmark <png>  (~156x32 HOLODOR wordmark -> OpenABL View/View.c @ 3x)

Usage:
  ./scripts/import-ssalmon-art.py --icon icon.png --splash splash.png --wordmark wordmark.png [--build-abl]
"""

import argparse
import os
import shutil
import subprocess
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO_ROOT, "scripts"))
from importlib.machinery import SourceFileLoader

apk_builder = SourceFileLoader(
    "build_boot_holodor_apk",
    os.path.join(REPO_ROOT, "scripts", "build-boot-holodor-apk.py"),
).load_module()


def encode_rle_palette_c_header(
    png_path: str, prefix: str
) -> tuple[int, int, str]:
    """
    Decode a PNG and encode it as an indexed palette + RLE byte stream C header.
    Each RLE packet is 2 bytes: (run_length 1..255, palette_index 0..255).
    Palette entries are 32-bit 0xAARRGGBB.
    """
    w, h, rgba = apk_builder.decode_simple_png_rgba(open(png_path, "rb").read())
    palette: list[int] = []
    color_to_idx: dict[int, int] = {}
    indices: list[int] = []

    for i in range(w * h):
        r, g, b, a = rgba[i * 4 : i * 4 + 4]
        argb = (0 if a < 128 else ((a << 24) | (r << 16) | (g << 8) | b))
        if argb not in color_to_idx:
            assert len(palette) < 256, f"{png_path} has >256 unique colors ({len(palette)})"
            color_to_idx[argb] = len(palette)
            palette.append(argb)
        indices.append(color_to_idx[argb])

    rle = bytearray()
    i = 0
    n = len(indices)
    while i < n:
        idx = indices[i]
        run = 1
        while i + run < n and indices[i + run] == idx and run < 255:
            run += 1
        rle.append(run)
        rle.append(idx)
        i += run

    pal_lines = ", ".join(f"0x{c:08X}U" for c in palette)
    rle_lines = []
    for off in range(0, len(rle), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in rle[off : off + 16])
        rle_lines.append(f"  {chunk},")

    header = (
        f"/* Auto-generated by scripts/import-ssalmon-art.py from {os.path.basename(png_path)} */\n"
        f"#pragma once\n\n"
        f"#define {prefix}_W {w}\n"
        f"#define {prefix}_H {h}\n"
        f"#define {prefix}_PALETTE_COUNT {len(palette)}\n"
        f"#define {prefix}_RLE_SIZE {len(rle)}\n\n"
        f"STATIC CONST UINT32 g{prefix}Palette[{len(palette)}] = {{\n  {pal_lines}\n}};\n\n"
        f"STATIC CONST UINT8 g{prefix}Rle[{len(rle)}] = {{\n"
        + "\n".join(rle_lines)
        + "\n};\n"
    )
    return w, h, header


def main() -> None:
    parser = argparse.ArgumentParser(description="Import ssalmon artwork into BootHolodor.apk and OpenABL")
    parser.add_argument("--icon", help="Path to 64x64 or 32x32 Holodor head icon PNG")
    parser.add_argument("--splash", help="Path to 240x135 Act 1 boot splash PNG")
    parser.add_argument("--wordmark", help="Path to ~156x32 HOLODOR wordmark PNG")
    parser.add_argument("--build-abl", action="store_true", help="Run scripts/build-openabl.sh after updating headers")
    args = parser.parse_args()

    assets_dir = os.path.join(REPO_ROOT, "assets", "ssalmon")
    os.makedirs(assets_dir, exist_ok=True)

    if args.icon:
        dst_icon = os.path.join(assets_dir, "icon.png")
        shutil.copyfile(args.icon, dst_icon)
        os.makedirs(os.path.join(REPO_ROOT, "docs", "images"), exist_ok=True)
        shutil.copyfile(args.icon, os.path.join(REPO_ROOT, "docs", "images", "holodor-icon.png"))
        print(f"==> Installed icon to {dst_icon} and rebuilding BootHolodor.apk...")
        subprocess.run(
            [
                sys.executable,
                os.path.join(REPO_ROOT, "scripts", "build-boot-holodor-apk.py"),
                os.path.join(REPO_ROOT, "packages", "holodor-bootloader-sm8750", "BootHolodor.apk"),
                os.path.join(REPO_ROOT, "packages", "holodor-bootloader-sm8550", "BootHolodor.apk"),
                os.path.join(REPO_ROOT, "packages", "holodor-bootloader-sm8250", "BootHolodor.apk"),
                os.path.join(REPO_ROOT, "docs", "BootHolodor.apk"),
            ],
            check=True,
        )

    openabl_dir = os.path.join(REPO_ROOT, "build", "competitors", "OpenABL")
    if args.splash:
        dst_splash = os.path.join(assets_dir, "splash.png")
        shutil.copyfile(args.splash, dst_splash)
        w, h, hdr = encode_rle_palette_c_header(dst_splash, "HolodorSplash")
        hdr_path = os.path.join(assets_dir, "HolodorSplashArt.h")
        open(hdr_path, "w").write(hdr)
        print(f"==> Generated {hdr_path} ({w}x{h})")
        if os.path.isdir(os.path.join(openabl_dir, "Menu")):
            shutil.copyfile(hdr_path, os.path.join(openabl_dir, "Menu", "HolodorSplashArt.h"))

    if args.wordmark:
        dst_wm = os.path.join(assets_dir, "wordmark.png")
        shutil.copyfile(args.wordmark, dst_wm)
        w, h, hdr = encode_rle_palette_c_header(dst_wm, "HolodorWordmark")
        hdr_path = os.path.join(assets_dir, "HolodorWordmarkArt.h")
        open(hdr_path, "w").write(hdr)
        print(f"==> Generated {hdr_path} ({w}x{h})")
        if os.path.isdir(os.path.join(openabl_dir, "View")):
            shutil.copyfile(hdr_path, os.path.join(openabl_dir, "View", "HolodorWordmarkArt.h"))

    if args.build_abl:
        subprocess.run([os.path.join(REPO_ROOT, "scripts", "build-openabl.sh")], check=True)


if __name__ == "__main__":
    main()
